// Developer tool: walks the notch through its states and saves a PNG of each (RAY_NOTCH_SHOTS=dir).
'use strict';
const fs = require('fs');
const path = require('path');
module.exports = async ({ win, ui, send, handleCommand, dir }) => {
  const wait = (ms) => new Promise((r) => setTimeout(r, ms));
  const shot = async (name) => {
    await wait(700);
    const img = await win.webContents.capturePage();
    fs.writeFileSync(path.join(dir, `${name}.png`), img.toPNG());
  };
  const js = (code) => win.webContents.executeJavaScript(code);
  fs.mkdirSync(dir, { recursive: true });
  await wait(1500);
  await shot('01-idle');
  ui({ phase: 'listening', mode: 'command', text: '' });
  await shot('02-listening-empty');
  ui({ phase: 'listening', mode: 'command', text: 'Open Spotify and set a timer for ten' });
  await shot('03-listening-words');
  ui({ phase: 'working', text: 'Play Billie Jean on Spotify', step: 'Opening Spotify' });
  await shot('04-working');
  ui({ phase: 'done', text: 'Timer set for 10 minutes.' });
  await shot('05-done');
  ui({ phase: 'answer', question: 'What is on my calendar today?', text: 'You have two things today:\n• 11:00 Stand-up with the team (30 min)\n• 16:30 Call with Arun about the launch.\nNothing after 6 pm.' });
  await shot('06-answer');
  ui({ phase: 'approve', id: 'x', text: 'Send the slides to Sam on WhatsApp?' });
  await shot('07-approve');
  ui({ phase: 'ask', id: 'y', why: 'Booking your Chennai trip', text: 'Which flight should I book?', options: ['7pm IndiGo ₹4,280', '9pm Air India ₹5,100', 'Neither'] });
  await shot('08-ask');
  ui({ phase: 'idle' });
  send('widget', { type: 'timer', seconds: 581, label: 'pasta' });
  await js("document.querySelector('#card').classList.add('hidden')");
  await shot('09-idle-timer');
  send('playing', { title: 'Paper Sky', artist: 'Lumen Coast', app: 'Spotify', playing: true, position: 62, duration: 194, at: Date.now() });
  send('todos', [{ id: 1, text: 'Milk', done: false }, { id: 2, text: 'Call Arun about launch', done: false }, { id: 3, text: 'Pay electricity bill', done: true, doneAt: Date.now() }]);
  await js("document.querySelector('#notch').click()");
  await shot('10-panel-home');
  await js("document.querySelector('[data-tab=list]').click()");
  await shot('11-panel-list');
  await js("document.querySelector('[data-tab=settings]').click()");
  await shot('12-panel-settings');
  await js("document.querySelector('[data-style=ring]').click(); document.querySelector('[data-color=orange]').click(); document.querySelector('[data-tab=home]').click(); document.querySelector('#panel').classList.add('hidden')");
  ui({ phase: 'listening', mode: 'dictate', text: 'Hey Sam, running late — see you at' });
  await shot('13-ring-orange-dictate');
  await js("document.querySelector('[data-tab=settings]') && 0");
  await handleCommand('Set a timer for 2 minutes');
  await shot('14-real-command-timer');
  process.exit(0);
};
